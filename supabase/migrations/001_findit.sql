-- FindIT on Supabase: full schema (replaces schema.sql + migrations 001-009 of the PHP version).
-- Run once in Supabase > SQL Editor. Safe to run again (IF NOT EXISTS everywhere).
-- Table and column names are unchanged from the PHP app, so existing data can be imported as-is.
-- Only the new things are: item.photo_path (camera/upload photo, stored in Storage), backup_run (backup log).

BEGIN;

CREATE TABLE IF NOT EXISTS public."User" (
    id_user        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_kampus   text NOT NULL,            -- encrypted by the app
    name_user      text NOT NULL,            -- encrypted
    password_user  varchar(255) NOT NULL,    -- bcrypt hash
    no_telp        text NOT NULL,            -- encrypted
    role_user      varchar(20) NOT NULL,
    created_at     timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    id_nim         text,                     -- encrypted
    email_bidx     varchar(64),              -- blind index (HMAC) for lookups
    nim_bidx       varchar(64)
);
CREATE UNIQUE INDEX IF NOT EXISTS user_email_bidx_key ON public."User" (email_bidx);
CREATE UNIQUE INDEX IF NOT EXISTS user_nim_bidx_key   ON public."User" (nim_bidx);

CREATE TABLE IF NOT EXISTS public.admin (
    id_admin       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_admin    varchar(100) NOT NULL UNIQUE,
    nama_admin     varchar(50)  NOT NULL,
    password_admin varchar(255) NOT NULL,
    level_access   varchar(20)  NOT NULL
);

CREATE TABLE IF NOT EXISTS public.category (
    id_category   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_category varchar(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.location (
    id_location      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tempat_ditemukan varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.item (
    kode_laporan        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_item             integer GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id_user_pelapor     integer NOT NULL REFERENCES public."User"(id_user) ON UPDATE CASCADE ON DELETE SET NULL,
    id_kategori         integer NOT NULL REFERENCES public.category(id_category) ON UPDATE CASCADE ON DELETE SET NULL,
    nama_barang         text NOT NULL,       -- encrypted
    detail_lokasi       text,                -- encrypted
    tanggal_ditemukan   date,
    ciri_umum           text,                -- encrypted
    ciri_khusus         text,                -- encrypted (never shown publicly)
    photo_path          text,                -- NEW: path inside the private "item-photos" Storage bucket
    status_barang       varchar(20) NOT NULL,   -- Found | Claimed
    created_at          timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    userid_user         integer,
    locationid_location integer REFERENCES public.location(id_location) ON UPDATE CASCADE ON DELETE SET NULL
);
-- NOT NULL + ON DELETE SET NULL is contradictory in the original schema; keep the original behaviour.
ALTER TABLE public.item ALTER COLUMN id_user_pelapor DROP NOT NULL;
ALTER TABLE public.item ALTER COLUMN id_kategori DROP NOT NULL;
ALTER TABLE public.item ADD COLUMN IF NOT EXISTS photo_path text;

CREATE TABLE IF NOT EXISTS public.claim (
    id_claim             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_klaim           varchar(50) NOT NULL UNIQUE,
    id_item              integer REFERENCES public.item(kode_laporan) ON UPDATE CASCADE ON DELETE SET NULL,
    id_user_pengaju      integer REFERENCES public."User"(id_user) ON UPDATE CASCADE ON DELETE SET NULL,
    id_admin_verifikator integer REFERENCES public.admin(id_admin) ON UPDATE CASCADE ON DELETE SET NULL,
    lokasi_kehilangan    text,               -- encrypted
    terakhir_di_lihat    text,               -- encrypted
    ciri_khusus_claim    text,               -- encrypted
    catatan_admin        text,               -- encrypted
    status_klaim         varchar(20),        -- Pending Verification | Approved | Rejected
    kode_pengambilan     text,               -- encrypted
    lokasi_pengambilan   text,               -- encrypted
    created_at           timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at           timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);
-- one claim per student per item (a rejected student cannot claim the same item again)
CREATE UNIQUE INDEX IF NOT EXISTS uq_claim_one_per_user_item ON public.claim (id_item, id_user_pengaju);

CREATE TABLE IF NOT EXISTS public.notification (
    id_notification bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_user     integer NOT NULL REFERENCES public."User"(id_user) ON DELETE CASCADE,
    id_claim    integer REFERENCES public.claim(id_claim) ON DELETE SET NULL,
    title       text NOT NULL,               -- encrypted
    message     text NOT NULL,               -- encrypted
    is_read     boolean NOT NULL DEFAULT FALSE,
    created_at  timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    type        varchar(40) NOT NULL DEFAULT 'general',
    severity    varchar(10) NOT NULL DEFAULT 'info' CONSTRAINT notification_severity_check CHECK (severity IN ('info','success','warning','danger')),
    id_item     integer REFERENCES public.item(kode_laporan) ON UPDATE CASCADE ON DELETE SET NULL,
    link        varchar(255),
    read_at     timestamp without time zone,
    dedupe_key  varchar(120)
);
CREATE UNIQUE INDEX IF NOT EXISTS notification_dedupe_key ON public.notification (id_user, dedupe_key) WHERE dedupe_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_notification_user_unread ON public.notification (id_user, is_read, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notification_user_created ON public.notification (id_user, created_at DESC, id_notification DESC);
CREATE INDEX IF NOT EXISTS idx_notification_user_unread_only ON public.notification (id_user) WHERE is_read = FALSE;

CREATE TABLE IF NOT EXISTS public.password_resets (
    id_reset   bigserial PRIMARY KEY,
    id_user    integer NOT NULL REFERENCES public."User"(id_user) ON DELETE CASCADE,
    token_hash char(64) NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    used_at    timestamptz,
    created_at timestamptz NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_password_resets_user    ON public.password_resets (id_user);
CREATE INDEX IF NOT EXISTS idx_password_resets_expires ON public.password_resets (expires_at);

CREATE TABLE IF NOT EXISTS public.pickup_token (
    id_pickup           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_claim            integer NOT NULL UNIQUE REFERENCES public.claim(id_claim) ON DELETE CASCADE,
    token_hash          char(64) NOT NULL UNIQUE,
    token_enc           text NOT NULL,
    created_at          timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    used_at             timestamp without time zone,
    id_admin_konfirmasi integer REFERENCES public.admin(id_admin),
    CONSTRAINT pickup_token_used_pair CHECK ((used_at IS NULL) = (id_admin_konfirmasi IS NULL))
);

CREATE TABLE IF NOT EXISTS public.user_photo (
    id_user       integer PRIMARY KEY REFERENCES public."User"(id_user) ON DELETE CASCADE,
    avatar_preset varchar(10),
    mime          varchar(20) CHECK (mime IN ('image/jpeg','image/png','image/webp')),
    foto_data     text,                      -- encrypted
    updated_at    timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_photo_one_source CHECK (
        (avatar_preset IS NOT NULL AND foto_data IS NULL AND mime IS NULL)
        OR (avatar_preset IS NULL AND foto_data IS NOT NULL AND mime IS NOT NULL))
);

-- NEW: log of backups and restores (the backup files themselves live in the private "findit-backups" bucket).
CREATE TABLE IF NOT EXISTS public.backup_run (
    id            text PRIMARY KEY,
    kind          varchar(12) NOT NULL,      -- daily | manual | restore
    status        varchar(20) NOT NULL,      -- RUNNING | SUCCESS | PARTIAL_SUCCESS | FAILED
    remote_status varchar(20),
    trigger_by    varchar(60),
    file          text,
    size_bytes    bigint,
    sha256        char(64),
    table_counts  jsonb,
    message       text,
    created_at    timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at   timestamp without time zone,
    file_deleted  boolean NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_backup_run_created ON public.backup_run (created_at DESC);

